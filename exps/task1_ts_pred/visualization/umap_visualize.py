#!/usr/bin/env python
"""UMAP visualisation for the time-series prediction task (task1_ts_pred) -- one model / one random seed.

Goal
----
For a given model (scDiTT first) on a given dataset (ZB first), draw the test time points generated by
**interpolation** and **extrapolation** in a single figure, and emit one separate image per training
random seed (seed=42..46).

Each figure = two side-by-side subplots:
  * left  "Ground Truth" : coloured by real cells at the test TPs
  * right the model name (e.g. scDiTT): coloured by generated cells at the test TPs
The background is a uniform grey (all real ground-truth cells).

Key design -- consistency across figures
----------------------
PCA / UMAP are fitted **once on the real data (ground truth)** with a fixed random_state.
The real data does not depend on the training seed, therefore:
  1. the grey background of the per-seed figures is **point-for-point identical**, which makes them
     directly comparable;
  2. other models / baselines later reuse the same cached embedding, so the background stays consistent.
The generated cells of each seed are projected through **the same fitted pca.transform + umap.transform**.

Data sources (read-only, never modified)
-------------------------
  <results_root>/<DS>/interpolation/seed<seed>/pred_genes.npy   object array of length T
  <results_root>/<DS>/extrapolation/seed<seed>/pred_genes.npy   generated cells at the test tps
  <results_root>/<DS>/<task>/seed<seed>/metrics.json            provides eval_tps
  <PROJ_ROOT>/<config.dataset.h5ad_path>                        real ground-truth cells
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import scanpy as sc
import scipy.sparse as sp
import yaml
from matplotlib.lines import Line2D
from sklearn.decomposition import PCA
from umap import UMAP

# ---------------------------------------------------------------------------
# ---------------------------------------------------------------------------
PROJ_ROOT = Path(__file__).resolve().parents[3]  # repository root

DEFAULT_RESULTS_ROOT = Path("")
DEFAULT_OUT_DIR = PROJ_ROOT / "results" / "task1_ts_pred_visualization"

GRAY = (173 / 255, 181 / 255, 189 / 255)

PCA_PCS = 50
UMAP_N_NEIGHBORS = 50
UMAP_MIN_DIST = 0.4
UMAP_SPREAD = 1.2
EMBED_SEED = 50

DEFAULT_EMBED_PARAMS = dict(pcs=PCA_PCS, n_neighbors=UMAP_N_NEIGHBORS,
                            min_dist=UMAP_MIN_DIST, spread=UMAP_SPREAD, repulsion=1.0)
DATASET_EMBED_PARAMS = {
    "ZB": dict(pcs=50, n_neighbors=50,  min_dist=0.4, spread=1.2, repulsion=1.0),
    "DR": dict(pcs=50, n_neighbors=100, min_dist=0.5, spread=1.0, repulsion=1.0),
    "SC": dict(pcs=50, n_neighbors=50,  min_dist=0.1, spread=3.0, repulsion=8.0),
    "MA": dict(pcs=50, n_neighbors=50,  min_dist=0.5, spread=1.0, repulsion=1.0),
}

CMAP_NAME = "magma"
CMAP_LO, CMAP_HI = 0.10, 0.90


# ---------------------------------------------------------------------------
# ---------------------------------------------------------------------------
def _densify(x) -> np.ndarray:
    if sp.issparse(x):
        x = x.toarray()
    return np.asarray(x, dtype=np.float32)


def tp_color_list(all_tps) -> dict:
    cm = plt.get_cmap(CMAP_NAME)
    n = len(all_tps)
    out = {}
    for i, t in enumerate(sorted(all_tps)):
        frac = 0.0 if n <= 1 else i / (n - 1)
        out[int(t)] = cm(CMAP_LO + (CMAP_HI - CMAP_LO) * frac)
    return out


def read_eval_tps(metrics_path: Path):
    with open(metrics_path) as f:
        return list(json.load(f)["eval_tps"])


def resolve_h5ad_path(config_path: Path) -> Path:
    with open(config_path) as f:
        cfg = yaml.safe_load(f)
    h5ad = Path(cfg["dataset"]["h5ad_path"])
    time_key = cfg["dataset"]["time_key"]
    if not h5ad.is_absolute():
        h5ad = PROJ_ROOT / h5ad
    return h5ad, time_key


# ---------------------------------------------------------------------------
# ---------------------------------------------------------------------------
def build_or_load_embedding(ds: str, h5ad_path: Path, time_key: str,
                            cache_dir: Path, refit: bool):
    import joblib

    cache_dir.mkdir(parents=True, exist_ok=True)
    cache_path = cache_dir / f"{ds}_umap_embedding.joblib"

    if cache_path.exists() and not refit:
        print(f"[embed] loaded cache: {cache_path}", flush=True)
        return joblib.load(cache_path)

    print(f"[embed] reading real data: {h5ad_path}", flush=True)
    adata = sc.read_h5ad(h5ad_path)
    all_tps = sorted(int(t) for t in np.unique(adata.obs[time_key]))
    print(f"[embed] {ds}: {adata.n_obs} cells x {adata.n_vars} genes, tps={all_tps}",
          flush=True)

    true_data = [_densify(adata[adata.obs[time_key] == t].X) for t in all_tps]
    X_true = np.concatenate(true_data, axis=0)
    true_cell_tps = np.concatenate(
        [np.full(each.shape[0], t, dtype=int) for t, each in zip(all_tps, true_data)]
    )

    p = DATASET_EMBED_PARAMS.get(ds, DEFAULT_EMBED_PARAMS)
    print(f"[embed] fit PCA({p['pcs']}) + UMAP "
          f"(nn={p['n_neighbors']}, min_dist={p['min_dist']}, spread={p['spread']}, "
          f"repulsion={p['repulsion']}, seed={EMBED_SEED}) ...", flush=True)
    pca = PCA(n_components=p["pcs"], svd_solver="arpack", random_state=EMBED_SEED)
    umap = UMAP(
        n_components=2,
        n_neighbors=p["n_neighbors"],
        min_dist=p["min_dist"],
        spread=p["spread"],
        repulsion_strength=p["repulsion"],
        random_state=EMBED_SEED,
    )
    true_pca = pca.fit_transform(X_true)
    true_umap = umap.fit_transform(true_pca)
    print("[embed] fit complete", flush=True)

    result = {
        "pca": pca,
        "umap": umap,
        "true_umap": true_umap,
        "true_cell_tps": true_cell_tps,
        "all_tps": all_tps,
        "n_genes": adata.n_vars,
        "embed_params": p,
    }
    joblib.dump(result, cache_path)
    print(f"[embed] cache saved: {cache_path}", flush=True)
    return result


# ---------------------------------------------------------------------------
# ---------------------------------------------------------------------------
def project_pred_test_cells(embed, pred_path: Path, test_tps, n_genes: int):
    pred = np.load(pred_path, allow_pickle=True)
    chunks, labels = [], []
    for t in test_tps:
        x = _densify(pred[t])
        if x.shape[1] != n_genes:
            raise ValueError(
                f"gene dimension mismatch: {pred_path} tp={t} has {x.shape[1]} columns, "
                f"real data {n_genes} columns"
            )
        chunks.append(x)
        labels.append(np.full(x.shape[0], t, dtype=int))
    if not chunks:
        return {}
    X = np.concatenate(chunks, axis=0)
    lab = np.concatenate(labels, axis=0)
    coords = embed["umap"].transform(embed["pca"].transform(X))
    return {int(t): coords[lab == t] for t in test_tps}


# ---------------------------------------------------------------------------
# ---------------------------------------------------------------------------
def plot_seed_figure(embed, pred_points, gt_test_tps, model_name, ds, seed,
                     colors, out_path, gray_s, color_s, dpi):
    true_umap = embed["true_umap"]
    true_cell_tps = embed["true_cell_tps"]

    highlight_tps = sorted(pred_points.keys())

    xmin, xmax = true_umap[:, 0].min(), true_umap[:, 0].max()
    ymin, ymax = true_umap[:, 1].min(), true_umap[:, 1].max()
    mx, my = 0.05 * (xmax - xmin), 0.05 * (ymax - ymin)
    xlim, ylim = (xmin - mx, xmax + mx), (ymin - my, ymax + my)

    fig, axes = plt.subplots(1, 2, figsize=(15, 7.5))

    for ax in axes:
        ax.scatter(true_umap[:, 0], true_umap[:, 1],
                   color=GRAY, s=gray_s, alpha=0.45, linewidths=0, rasterized=True)
        ax.set_xlim(*xlim)
        ax.set_ylim(*ylim)
        ax.set_aspect("equal", adjustable="box")
        ax.set_xticks([])
        ax.set_yticks([])
        for spine in ax.spines.values():
            spine.set_visible(True)
            spine.set_edgecolor("0.3")
            spine.set_linewidth(1.2)

    ax_gt = axes[0]
    for t in highlight_tps:
        if t not in gt_test_tps:
            continue
        idx = np.where(true_cell_tps == t)[0]
        ax_gt.scatter(true_umap[idx, 0], true_umap[idx, 1],
                      color=colors[t], s=color_s, alpha=0.95, linewidths=0,
                      rasterized=True)
    ax_gt.set_title("Ground Truth", fontsize=20, fontfamily="serif", pad=12)

    ax_pred = axes[1]
    for t in highlight_tps:
        coords = pred_points[t]
        ax_pred.scatter(coords[:, 0], coords[:, 1],
                        color=colors[t], s=color_s, alpha=0.95, linewidths=0,
                        rasterized=True)
    ax_pred.set_title(model_name, fontsize=20, fontfamily="serif", pad=12)

    handles = []
    for t in highlight_tps:
        handles.append(
            Line2D([0], [0], marker="o", linestyle="none", markersize=9,
                   markerfacecolor=colors[t], markeredgecolor="none",
                   label=f"{t}")
        )
    handles.append(
        Line2D([0], [0], marker="o", linestyle="none", markersize=9,
               markerfacecolor=GRAY, markeredgecolor="none", label="others")
    )
    leg = fig.legend(handles=handles, loc="center left", bbox_to_anchor=(0.87, 0.5),
                     fontsize=13, frameon=True, fancybox=True, handletextpad=0.4,
                     title="test TP", title_fontsize=13)
    leg.get_frame().set_boxstyle("round,pad=0.5,rounding_size=0.25")
    leg.get_frame().set_edgecolor("0.75")
    leg.get_frame().set_linewidth(1.2)
    leg.get_frame().set_facecolor("white")

    fig.text(0.44, 0.075, f"{ds} dataset", ha="center", va="center",
             fontsize=17, fontfamily="serif", fontweight="bold")
    fig.text(0.44, 0.03, f"seed = {seed}", ha="center", va="center",
             fontsize=14, fontfamily="serif")

    fig.subplots_adjust(left=0.01, right=0.86, top=0.92, bottom=0.14, wspace=0.04)
    fig.savefig(out_path, dpi=dpi, facecolor="white")
    plt.close(fig)
    print(f"[plot] saved: {out_path}", flush=True)


# ---------------------------------------------------------------------------
# main
# ---------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results-root", type=Path, default=DEFAULT_RESULTS_ROOT,
                    help="read-only experiment results root")
    ap.add_argument("--dataset", default="ZB", help="dataset name (the sub-directory name under the results directory)")
    ap.add_argument("--model-name", default="scDiTT", help="model name used in the right-hand title and in the output filename")
    ap.add_argument("--seeds", type=int, nargs="+", default=[42, 43, 44, 45, 46])
    ap.add_argument("--interp-task", default="interpolation")
    ap.add_argument("--extrap-task", default="extrapolation")
    ap.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    ap.add_argument("--refit", action="store_true", help="force refitting the embedding (ignore the cache)")
    ap.add_argument("--gray-size", type=float, default=6.0, help="size of the grey background points")
    ap.add_argument("--color-size", type=float, default=5.0, help="size of the coloured test points")
    ap.add_argument("--dpi", type=int, default=200)
    args = ap.parse_args()

    ds = args.dataset
    rroot = args.results_root
    args.out_dir.mkdir(parents=True, exist_ok=True)

    ref_seed = args.seeds[0]
    interp_seed_dir = rroot / ds / args.interp_task / f"seed{ref_seed}"
    extrap_seed_dir = rroot / ds / args.extrap_task / f"seed{ref_seed}"
    h5ad_path, time_key = resolve_h5ad_path(interp_seed_dir / "config.yaml")
    if not h5ad_path.exists():
        raise FileNotFoundError(f"real-data h5ad not found: {h5ad_path}")

    interp_tps = read_eval_tps(interp_seed_dir / "metrics.json")
    extrap_tps = read_eval_tps(extrap_seed_dir / "metrics.json")
    gt_test_tps = sorted(set(interp_tps) | set(extrap_tps))
    print(f"[main] {ds}: interp_tps={interp_tps}  extrap_tps={extrap_tps}", flush=True)

    embed = build_or_load_embedding(
        ds, h5ad_path, time_key,
        cache_dir=args.out_dir / "_embedding_cache", refit=args.refit,
    )
    colors = tp_color_list(embed["all_tps"])
    n_genes = embed["n_genes"]

    for seed in args.seeds:
        i_dir = rroot / ds / args.interp_task / f"seed{seed}"
        e_dir = rroot / ds / args.extrap_task / f"seed{seed}"
        i_pred = i_dir / "pred_genes.npy"
        e_pred = e_dir / "pred_genes.npy"
        if not i_pred.exists() or not e_pred.exists():
            print(f"[warn] seed{seed}: missing pred_genes.npy, skipping", flush=True)
            continue

        i_tps = read_eval_tps(i_dir / "metrics.json")
        e_tps = read_eval_tps(e_dir / "metrics.json")

        extrap_only = [t for t in e_tps if t not in set(i_tps)]
        overlap = sorted(set(i_tps) & set(e_tps))
        if overlap:
            print(f"[warn] seed{seed}: tp {overlap} is a test point for both interpolation and extrapolation, "
                  f"taking the interpolation result; extrapolation only contributes {extrap_only}", flush=True)

        pred_points = {}
        pred_points.update(project_pred_test_cells(embed, i_pred, i_tps, n_genes))
        pred_points.update(project_pred_test_cells(embed, e_pred, extrap_only, n_genes))

        ds_out = args.out_dir / ds
        ds_out.mkdir(parents=True, exist_ok=True)
        out_path = ds_out / f"{ds}_{args.model_name}_seed{seed}.png"
        plot_seed_figure(
            embed, pred_points, gt_test_tps, args.model_name, ds, seed,
            colors, out_path, gray_s=args.gray_size, color_s=args.color_size,
            dpi=args.dpi,
        )

    print("[main] done.", flush=True)


if __name__ == "__main__":
    main()
